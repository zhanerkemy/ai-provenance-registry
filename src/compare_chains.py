"""Check that Anvil and Sepolia charge the same gas for the same transactions.

Run after both replays (Anvil full tree, Sepolia sample):
    python src/compare_chains.py

Our numbers come from Anvil, a chain on our own laptop. Gas is set by the EVM rules,
not by the network, so Sepolia should give exactly the same numbers. This script
checks it, and any difference is reported, not hidden.

Writes data/results/chain_check.json (the comparison) and docs/deployments.md
(Sepolia contract addresses and blocks).
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ETHERSCAN = "https://sepolia.etherscan.io"


def read_rows(path: Path) -> dict[tuple, dict]:
    """Transactions keyed by (design, batch_size, model_id). For Merkle only the first
    row of each batch carries the transaction's gas, so only those rows are kept."""
    with path.open(newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if int(r["tx_gas"]) > 0]
    return {(r["design"], int(r["batch_size"]), r["model_id"]): r for r in rows}


def compare(anvil: dict, public: dict, anvil_meta: dict, public_meta: dict) -> dict:
    differences = []
    for key, row in public.items():
        if key not in anvil:
            raise KeyError(f"{key} is not in the Anvil results; run both with the same tree")
        a, p = int(anvil[key]["tx_gas"]), int(row["tx_gas"])
        if a != p:
            differences.append({"design": key[0], "batch_size": key[1], "model_id": key[2],
                                "anvil_gas": a, "sepolia_gas": p, "difference": p - a})

    deploys = []
    anvil_deploys = {(c["design"], c["batch_size"]): c for c in anvil_meta.get("contracts", [])}
    for c in public_meta["contracts"]:
        a = anvil_deploys.get((c["design"], c["batch_size"]))
        deploys.append({"design": c["design"], "batch_size": c["batch_size"],
                        "anvil_gas": a["deploy_gas"] if a else None,
                        "sepolia_gas": c["deploy_gas"],
                        "identical": bool(a) and a["deploy_gas"] == c["deploy_gas"]})

    return {
        "anvil_run_at_utc": anvil_meta["run_at_utc"],
        "sepolia_run_at_utc": public_meta["run_at_utc"],
        "sepolia_block_range": public_meta["block_range"],
        "same_tree_file": anvil_meta["tree_file_sha256"] == public_meta["tree_file_sha256"],
        "same_compiler": anvil_meta["solc"] == public_meta["solc"],
        "transactions_compared": len(public),
        "transactions_identical": len(public) - len(differences),
        "differences": differences,
        "deployments": deploys,
    }


def deployments_markdown(meta: dict) -> str:
    lines = [
        "# Deployments",
        "",
        "Generated by `src/compare_chains.py` from `data/results/sepolia/run_meta.json`;",
        "do not edit by hand.",
        "",
        f"- Network: Sepolia (chain id {meta['chain_id']})",
        f"- Run at (UTC): {meta['run_at_utc']}",
        f"- Sender: [{meta['sender']}]({ETHERSCAN}/address/{meta['sender']})",
        f"- Block range: {meta['block_range'][0]} to {meta['block_range'][1]}",
        f"- Compiler: solc {meta['solc']}",
        f"- Models registered: the first {meta['n_registered']} of {meta['n_registrable']}"
        " registrable models (breadth-first order)",
        "",
        "| Design | Batch size | Contract | Deployed in block | Deployment transaction |",
        "|---|---|---|---|---|",
    ]
    for c in meta["contracts"]:
        k = c["batch_size"] if c["design"] == "merkle" else "-"
        lines.append(f"| {c['design']} | {k} | [{c['address']}]({ETHERSCAN}/address/{c['address']})"
                     f" | {c['deploy_block']} | [{c['deploy_tx'][:10]}...]"
                     f"({ETHERSCAN}/tx/{c['deploy_tx']}) |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Compare Anvil and Sepolia gas.")
    parser.add_argument("--anvil", type=Path, default=Path("data/results"))
    parser.add_argument("--public", type=Path, default=Path("data/results/sepolia"))
    parser.add_argument("--out", type=Path, default=Path("data/results/chain_check.json"))
    parser.add_argument("--deployments", type=Path, default=Path("docs/deployments.md"))
    args = parser.parse_args()

    anvil_meta = json.loads((args.anvil / "run_meta.json").read_text(encoding="utf-8"))
    public_meta = json.loads((args.public / "run_meta.json").read_text(encoding="utf-8"))
    result = compare(read_rows(args.anvil / "gas.csv"), read_rows(args.public / "gas.csv"),
                     anvil_meta, public_meta)

    args.out.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8", newline="\n")
    args.deployments.parent.mkdir(parents=True, exist_ok=True)
    args.deployments.write_text(deployments_markdown(public_meta), encoding="utf-8",
                                newline="\n")

    print(f"{result['transactions_identical']} of {result['transactions_compared']} "
          "transactions used identical gas on both chains")
    for d in result["differences"]:
        print(f"  differs: {d}")
    print(f"Wrote {args.out} and {args.deployments}")


if __name__ == "__main__":
    main()
